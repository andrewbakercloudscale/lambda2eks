HEALTH_PATH = "/_lambda2eks/healthz"
PORT = 8080


class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data: Any) -> bool:
        return True


def _str_presenter(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_presenter)


def dump_yaml(docs: list[dict[str, Any]]) -> str:
    return "---\n".join(yaml.dump(d, Dumper=_Dumper, sort_keys=False, default_flow_style=False) for d in docs)


# ------------------------------------------------------------------ build context

def runtime_tag(runtime: str) -> str:
    if runtime.startswith("python"):
        return runtime.removeprefix("python")
    m = re.match(r"nodejs(\d+)", runtime)
    if not m:
        raise ValueError(f"no base image for runtime {runtime}")
    return m.group(1)


def dockerfile(plan: Plan, src_present: bool) -> str:
    spec = plan.spec
    family = spec.runtime_family
    lines = ["# Generated by lambda2eks. The Lambda base image keeps the runtime, OS libraries and AWS SDK the function had."]
    if spec.image_uri:
        lines.append(f"FROM {spec.image_uri}")
    elif family == "python":
        lines += [f"FROM public.ecr.aws/lambda/python:{runtime_tag(spec.runtime)}", "COPY src/ ${LAMBDA_TASK_ROOT}/"]
        if src_present and (spec.code_dir / "requirements.txt").is_file():
            lines.append("RUN pip install --no-cache-dir -r ${LAMBDA_TASK_ROOT}/requirements.txt -t ${LAMBDA_TASK_ROOT}")
    else:
        lines += [f"FROM public.ecr.aws/lambda/nodejs:{runtime_tag(spec.runtime)}", "COPY src/ ${LAMBDA_TASK_ROOT}/"]
        if src_present and (spec.code_dir / "package.json").is_file():
            lock = (spec.code_dir / "package-lock.json").is_file()
            lines.append("RUN cd ${LAMBDA_TASK_ROOT} && " + ("npm ci --omit=dev" if lock else "npm install --omit=dev"))
    if family == "python":
        lines += [
            "COPY lambda2eks-shim.py /opt/lambda2eks/shim.py",
            "ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PYTHONPATH=/var/task:/var/runtime",
            "USER 1000:1000",
            'ENTRYPOINT ["python3", "/opt/lambda2eks/shim.py"]',
        ]
    else:
        lines += [
            "COPY lambda2eks-shim.mjs /opt/lambda2eks/shim.mjs",
            "USER 1000:1000",
            'ENTRYPOINT ["node", "/opt/lambda2eks/shim.mjs"]',
        ]
    lines.append("CMD []")
    return "\n".join(lines) + "\n"


def write_build_context(plan: Plan, out: Path) -> None:
    spec = plan.spec
    src_dst = out / "src"
    src_present = bool(spec.code_dir and spec.code_dir.is_dir())
    if src_present and spec.code_dir.resolve() != src_dst.resolve():
        if src_dst.exists():
            shutil.rmtree(src_dst)
        has_pkg = (spec.code_dir / "package.json").is_file()
        ignore = shutil.ignore_patterns(".aws-sam", ".git", "__pycache__", ".venv", "*.pyc", ".env*",
                                        *(["node_modules"] if has_pkg else []))
        shutil.copytree(spec.code_dir, src_dst, ignore=ignore)
    elif not spec.image_uri:
        src_dst.mkdir(exist_ok=True)

    shim = "shim.py" if spec.runtime_family == "python" else "shim.mjs"
    (out / f"lambda2eks-{shim}").write_text(resources.files("lambda2eks.shims").joinpath(shim).read_text())
    (out / "Dockerfile").write_text(dockerfile(plan, src_present))
    (out / ".dockerignore").write_text("k8s/\niam/\nai/\nMIGRATION.md\nbuild.sh\n")
    build = out / "build.sh"
    build.write_text(
        "#!/usr/bin/env bash\n"
        "# Build and push the image for this function. Override IMAGE to change the destination.\n"
        "set -euo pipefail\n"
        f'IMAGE="${{IMAGE:-{plan.image}}}"\n'
        'cd "$(dirname "$0")"\n'
        f'docker buildx build --platform linux/{spec.arch} -t "$IMAGE" --push .\n'
    )
    build.chmod(0o755)


# ------------------------------------------------------------------ manifests

def _labels(plan: Plan, component: str | None = None) -> dict[str, str]:
    labels = {"app.kubernetes.io/name": plan.k8s_name, "app.kubernetes.io/managed-by": "lambda2eks"}
    if component:
        labels["app.kubernetes.io/component"] = component
    return labels


def _base_env(plan: Plan, mode: str, region: str) -> list[dict[str, str]]:
    spec = plan.spec
    env = {
        "L2E_MODE": mode,
        "L2E_HANDLER": spec.handler or "REPLACE_ME",
        "L2E_TIMEOUT_S": str(spec.timeout_s),
        "L2E_CONCURRENCY": str(plan.concurrency),
        "AWS_LAMBDA_FUNCTION_NAME": spec.name,
        "AWS_LAMBDA_FUNCTION_MEMORY_SIZE": str(spec.memory_mb),
        "AWS_LAMBDA_FUNCTION_VERSION": "$LATEST",
        "AWS_REGION": region,
        "AWS_DEFAULT_REGION": region,
    }
    if spec.account_id:
        env["L2E_ACCOUNT_ID"] = spec.account_id
    return [{"name": k, "value": v} for k, v in env.items()]


def _pod_spec(plan: Plan, workload: Workload, mode_env: list[dict[str, str]], region: str,
              http: bool, restart: str | None = None, grace: int = 30) -> dict[str, Any]:
    spec = plan.spec
    env_from = []
    if set(spec.environment) - set(plan.secret_env_keys):
        env_from.append({"configMapRef": {"name": f"{plan.k8s_name}-env"}})
    if plan.secret_env_keys:
        env_from.append({"secretRef": {"name": f"{plan.k8s_name}-secrets"}})
    container: dict[str, Any] = {
        "name": "function",
        "image": plan.image,
        "env": _base_env(plan, workload_mode(workload), region) + mode_env,
        **({"envFrom": env_from} if env_from else {}),
        "resources": {
            "requests": {"cpu": f"{plan.cpu_millicores}m", "memory": f"{plan.memory_mb}Mi"},
            "limits": {"memory": f"{plan.memory_mb}Mi"},
        },
        "securityContext": {
            "runAsNonRoot": True, "runAsUser": 1000, "runAsGroup": 1000, "readOnlyRootFilesystem": True,
            "allowPrivilegeEscalation": False, "capabilities": {"drop": ["ALL"]},
        },
        "volumeMounts": [{"name": "tmp", "mountPath": "/tmp"}],
    }
    if http:
        container["ports"] = [{"name": "http", "containerPort": PORT}]
        probe = {"httpGet": {"path": HEALTH_PATH, "port": "http"}, "periodSeconds": 10}
        container["readinessProbe"] = {**probe, "initialDelaySeconds": 2}
        container["livenessProbe"] = {**probe, "initialDelaySeconds": 10, "failureThreshold": 6}
    pod: dict[str, Any] = {
        "serviceAccountName": plan.k8s_name,
        "terminationGracePeriodSeconds": grace,
        "containers": [container],
        "volumes": [{"name": "tmp", "emptyDir": {"sizeLimit": f"{spec.ephemeral_storage_mb}Mi"}}],
        "nodeSelector": {"kubernetes.io/arch": spec.arch},
    }
    if restart:
        pod["restartPolicy"] = restart
    return pod


def workload_mode(w: Workload) -> str:
    return {HTTP: "http", INVOKE: "http", SQS: "sqs", SCHEDULE: "schedule"}[w.kind]


def _deployment(plan: Plan, w: Workload, replicas: int, pod: dict[str, Any]) -> dict[str, Any]:
    labels = _labels(plan, w.name)
    return {
        "apiVersion": "apps/v1", "kind": "Deployment",
        "metadata": {"name": w.name, "labels": labels},
        "spec": {
            "replicas": replicas,
            "selector": {"matchLabels": {"app.kubernetes.io/name": plan.k8s_name, "app.kubernetes.io/component": w.name}},
            "template": {"metadata": {"labels": labels}, "spec": pod},
        },
    }


def _ingress_paths(routes: list[dict[str, Any]]) -> list[str]:
    prefixes = set()
    for r in routes:
        p = r.get("path")
        if not p:
            return ["/"]
        head = p.split("{", 1)[0].rstrip("/") or "/"
        prefixes.add(head)
    return sorted(prefixes)


def http_docs(plan: Plan, w: Workload, region: str) -> list[dict[str, Any]]:
    spec = plan.spec
    mode_env = [{"name": "L2E_PORT", "value": str(PORT)}]
    if w.kind == HTTP:
        mode_env += [
            {"name": "L2E_HTTP_EVENT_FORMAT", "value": w.trigger.details["event_format"]},
            {"name": "L2E_HTTP_ROUTES", "value": json.dumps([r for r in w.trigger.details["routes"] if r.get("path")])},
        ]
    grace = max(30, spec.timeout_s + 10)
    docs = [_deployment(plan, w, plan.http_min_replicas, _pod_spec(plan, w, mode_env, region, http=True, grace=grace))]
    selector = {"app.kubernetes.io/name": plan.k8s_name, "app.kubernetes.io/component": w.name}
    docs.append({
        "apiVersion": "v1", "kind": "Service",
        "metadata": {"name": w.name, "labels": _labels(plan, w.name)},
        "spec": {"selector": selector, "ports": [{"name": "http", "port": 80, "targetPort": "http"}]},
    })
    docs.append({
        "apiVersion": "autoscaling/v2", "kind": "HorizontalPodAutoscaler",
        "metadata": {"name": w.name, "labels": _labels(plan, w.name)},
        "spec": {
            "scaleTargetRef": {"apiVersion": "apps/v1", "kind": "Deployment", "name": w.name},
            "minReplicas": plan.http_min_replicas, "maxReplicas": plan.http_max_replicas,
            "metrics": [{"type": "Resource", "resource": {"name": "cpu", "target": {"type": "Utilization", "averageUtilization": 70}}}],
        },
    })
    if plan.http_min_replicas >= 2:
        docs.append({
            "apiVersion": "policy/v1", "kind": "PodDisruptionBudget",
            "metadata": {"name": w.name, "labels": _labels(plan, w.name)},
            "spec": {"minAvailable": 1, "selector": {"matchLabels": selector}},
        })
    if w.kind == HTTP:
        idle = max(60, spec.timeout_s + 5)
        docs.append({
            "apiVersion": "networking.k8s.io/v1", "kind": "Ingress",
            "metadata": {"name": w.name, "labels": _labels(plan, w.name), "annotations": {
                "alb.ingress.kubernetes.io/scheme": plan.ingress_scheme,
                "alb.ingress.kubernetes.io/target-type": "ip",
                "alb.ingress.kubernetes.io/healthcheck-path": HEALTH_PATH,
                "alb.ingress.kubernetes.io/load-balancer-attributes": f"idle_timeout.timeout_seconds={idle}",
            }},
            "spec": {"ingressClassName": "alb", "rules": [{"http": {"paths": [
                {"path": p, "pathType": "Prefix", "backend": {"service": {"name": w.name, "port": {"name": "http"}}}}
                for p in _ingress_paths(w.trigger.details["routes"])
            ]}}]},
        })
    return docs


def sqs_docs(plan: Plan, w: Workload, region: str, iam_mode: str) -> list[dict[str, Any]]:
    d = w.trigger.details
    url = d.get("queue_url") or "REPLACE_ME"
    mode_env = [
        {"name": "L2E_SQS_QUEUE_URL", "value": url},
        {"name": "L2E_SQS_QUEUE_ARN", "value": d.get("queue_arn") or ""},
        {"name": "L2E_SQS_BATCH_SIZE", "value": str(d.get("batch_size", 10))},
        {"name": "L2E_SQS_REPORT_BATCH_ITEM_FAILURES", "value": "true" if d.get("report_batch_item_failures") else "false"},
    ]
    grace = plan.spec.timeout_s + 30  # one long poll (20 s) plus the batch in flight
    docs = [_deployment(plan, w, 1, _pod_spec(plan, w, mode_env, region, http=False, grace=grace))]
    pod_identity: dict[str, Any] = {"provider": "aws"}
    if iam_mode == "irsa":
        pod_identity["identityOwner"] = "workload"
    else:
        pod_identity["roleArn"] = plan.spec.role_arn or "REPLACE_ME"
    docs.append({
        "apiVersion": "keda.sh/v1alpha1", "kind": "TriggerAuthentication",
        "metadata": {"name": w.name, "labels": _labels(plan, w.name)},
        "spec": {"podIdentity": pod_identity},
    })
    docs.append({
        "apiVersion": "keda.sh/v1alpha1", "kind": "ScaledObject",
        "metadata": {"name": w.name, "labels": _labels(plan, w.name)},
        "spec": {
            "scaleTargetRef": {"name": w.name},
            "minReplicaCount": 0, "maxReplicaCount": plan.sqs_max_replicas,
            "pollingInterval": 15, "cooldownPeriod": 300,
            "triggers": [{"type": "aws-sqs-queue", "authenticationRef": {"name": w.name}, "metadata": {
                "queueURL": url, "queueLength": str(max(1, min(int(d.get("batch_size", 10)), 10)) * plan.concurrency),
                "awsRegion": region,
            }}],
        },
    })
    return docs


def schedule_docs(plan: Plan, w: Workload, region: str) -> list[dict[str, Any]]:
    d = w.trigger.details
    try:
        cron, warns = to_k8s_cron(d["expression"])
    except ScheduleError as e:
        cron, warns = "0 0 31 2 *", [f"{e}; the CronJob is set to a date that never occurs and suspended until you fix it"]
        d["suspended"] = True
    plan.spec.warnings.extend(warns)
    mode_env = []
    if d.get("input"):
        mode_env.append({"name": "L2E_SCHEDULE_INPUT", "value": d["input"]})
    if d.get("rule_arn"):
        mode_env.append({"name": "L2E_SCHEDULE_RULE_ARN", "value": d["rule_arn"]})
    pod = _pod_spec(plan, w, mode_env, region, http=False, restart="Never")
    labels = _labels(plan, w.name)
    return [{
        "apiVersion": "batch/v1", "kind": "CronJob",
        "metadata": {"name": w.name, "labels": labels, "annotations": {"lambda2eks/eventbridge-schedule": d["expression"]}},
        "spec": {
            "schedule": cron, "timeZone": "Etc/UTC", "suspend": bool(d.get("suspended")),
            "concurrencyPolicy": plan.schedule_concurrency_policy, "startingDeadlineSeconds": 300,
            "successfulJobsHistoryLimit": 3, "failedJobsHistoryLimit": 3,
            "jobTemplate": {"spec": {
                "backoffLimit": 2,  # Lambda retries a failed asynchronous invocation twice
                "activeDeadlineSeconds": plan.spec.timeout_s + 120,
                "ttlSecondsAfterFinished": 86400,
                "template": {"metadata": {"labels": labels}, "spec": pod},
            }},
        },
    }]


def manifests(plan: Plan, namespace: str, region: str, iam_mode: str) -> dict[str, list[dict[str, Any]]]:
    spec = plan.spec
    sa: dict[str, Any] = {"apiVersion": "v1", "kind": "ServiceAccount", "metadata": {"name": plan.k8s_name, "labels": _labels(plan)}}
    if iam_mode == "irsa":
        sa["metadata"]["annotations"] = {"eks.amazonaws.com/role-arn": spec.role_arn or "REPLACE_ME"}
    files: dict[str, list[dict[str, Any]]] = {"serviceaccount.yaml": [sa]}
    plain = {k: v for k, v in sorted(spec.environment.items()) if k not in plan.secret_env_keys}
    if plain:
        files["configmap.yaml"] = [{"apiVersion": "v1", "kind": "ConfigMap",
                                    "metadata": {"name": f"{plan.k8s_name}-env", "labels": _labels(plan)}, "data": plain}]
    if plan.secret_env_keys:
        files["secret.yaml"] = [{
            "apiVersion": "v1", "kind": "Secret", "type": "Opaque",
            "metadata": {"name": f"{plan.k8s_name}-secrets", "labels": _labels(plan),
                         "annotations": {"lambda2eks/note": "values are placeholders; load them from Secrets Manager or External Secrets"}},
            "stringData": {k: "REPLACE_ME" for k in plan.secret_env_keys},
        }]
    for w in plan.workloads:
        if w.kind in (HTTP, INVOKE):
            files[f"{w.name}.yaml"] = http_docs(plan, w, region)
        elif w.kind == SQS:
            files[f"{w.name}.yaml"] = sqs_docs(plan, w, region, iam_mode)
        elif w.kind == SCHEDULE:
            files[f"{w.name}.yaml"] = schedule_docs(plan, w, region)
    return files


def trust_policy(plan: Plan, namespace: str, iam_mode: str) -> dict[str, Any]:
    # Keep Lambda's own trust so the function keeps working until the cut-over is finished.
    statements: list[dict[str, Any]] = [
        {"Sid": "KeepLambdaDuringMigration", "Effect": "Allow", "Principal": {"Service": "lambda.amazonaws.com"}, "Action": "sts:AssumeRole"},
    ]
    if iam_mode == "irsa":
        provider = "oidc.eks.REGION.amazonaws.com/id/REPLACE_ME_OIDC_ID"
        statements.append({
            "Sid": "EksIrsa", "Effect": "Allow",
            "Principal": {"Federated": f"arn:aws:iam::{plan.spec.account_id or 'ACCOUNT_ID'}:oidc-provider/{provider}"},
            "Action": "sts:AssumeRoleWithWebIdentity",
            "Condition": {"StringEquals": {f"{provider}:sub": f"system:serviceaccount:{namespace}:{plan.k8s_name}",
                                           f"{provider}:aud": "sts.amazonaws.com"}},
        })
    else:
        statements.append({"Sid": "EksPodIdentity", "Effect": "Allow", "Principal": {"Service": "pods.eks.amazonaws.com"},
                           "Action": ["sts:AssumeRole", "sts:TagSession"]})
    return {"Version": "2012-10-17", "Statement": statements}


# ------------------------------------------------------------------ report

def _md_cell(v: Any) -> str:
    text = ", ".join(map(str, v)) if isinstance(v, list) else str(v)
    return text.replace("|", "\\|").replace("\n", " ") or "—"


def report(plan: Plan, namespace: str, iam_mode: str, files: dict[str, list[dict[str, Any]]], patch_files: list[str]) -> str:
    spec = plan.spec
    out = [f"# {spec.name} → EKS", ""]
    if not plan.supported:
        out += [f"**Not generated:** {plan.unsupported_reason}", ""]
    blockers = [f for f in plan.findings if f.get("severity") == "blocker"]
    if plan.ai_used:
        out += [f"**AI review** ({plan.ai_model}): {plan.ai_summary}", ""]
        if blockers:
            out += [f"**{len(blockers)} blocker(s) must be fixed before this runs on EKS.**", ""]
    else:
        out += ["**AI review: skipped (--no-ai).** Settings below are rule-based only; nobody has read the code.", ""]

    out += ["## Workloads", "", "| Workload | From | Kubernetes |", "|---|---|---|"]
    for w in plan.workloads:
        src = {HTTP: lambda: ", ".join(w.trigger.details["sources"]) + f" (payload {w.trigger.details['event_format']})",
               SQS: lambda: w.trigger.details.get("queue_arn") or "SQS queue (unresolved)",
               SCHEDULE: lambda: w.trigger.details["expression"],
               INVOKE: lambda: "direct Invoke API calls"}[w.kind]()
        k8s = ", ".join(d["kind"] for d in files.get(f"{w.name}.yaml", []))
        out.append(f"| `{w.name}` | {_md_cell(src)} | {k8s} |")
    out.append("")

    out += ["## Decisions", "", "| Setting | Value | Decided by | Reason |", "|---|---|---|---|"]
    kinds = {w.kind for w in plan.workloads}
    relevant = {
        "http_min_replicas": kinds & {HTTP, INVOKE}, "http_max_replicas": kinds & {HTTP, INVOKE},
        "ingress_scheme": kinds & {HTTP}, "sqs_max_replicas": kinds & {SQS}, "schedule_concurrency_policy": kinds & {SCHEDULE},
    }
    for d in plan.decisions.values():
        if d.setting in relevant and not relevant[d.setting]:
            continue
        by = "AI" + (f" (rule said {_md_cell(d.baseline)})" if d.baseline is not None else "") if d.source == "ai" else "rule"
        out.append(f"| {d.setting} | {_md_cell(d.value)} | {by} | {_md_cell(d.reason)} |")
    out.append("")

    if plan.findings:
        out += ["## Findings", ""]
        for f in plan.findings:
            loc = f" — `{f['file']}" + (f":{f['line']}" if f.get("line") else "") + "`" if f.get("file") else ""
            out += [f"- **{f['severity'].upper()}** {f['title']}{loc}", f"  {f['detail']}"]
        out.append("")
    if patch_files:
        out += ["## Suggested code changes", "", "Written for review, not applied. Check each one, then apply it with `git apply`:", ""]
        out += [f"- `{p}`" for p in patch_files] + [""]

    not_migrated = []
    if spec.layers:
        not_migrated.append(f"Layers ({', '.join(spec.layers)}): their files are not in the image. Add their contents to `src/` or the Dockerfile.")
    if spec.vpc:
        not_migrated.append("VPC config: pods use the cluster's VPC networking. Check that they can reach the same private resources (security groups for pods, if you use them).")
    if spec.dead_letter_target:
        not_migrated.append(f"Dead-letter target {spec.dead_letter_target}: async-invoke DLQs do not apply. SQS workers rely on the queue's redrive policy.")
    if any(w.kind == HTTP for w in plan.workloads):
        not_migrated.append("API Gateway features (authorizers, API keys, usage plans, throttling, CORS, custom domains) are not reproduced by the Ingress.")
    if plan.unsupported_triggers:
        advice = {a["trigger"]: a["recommendation"] for a in plan.trigger_advice}
        for t in plan.unsupported_triggers:
            rec = next((v for k, v in advice.items() if t.details.get("source", "") in k or t.details.get("detail", "") in k), None)
            not_migrated.append(f"Trigger not migrated: {t.details.get('detail')}" + (f" — AI advice: {rec}" if rec else ""))
    if not_migrated:
        out += ["## Not migrated", ""] + [f"- {x}" for x in not_migrated] + [""]

    role = spec.role_arn or "ROLE_ARN"
    role_name = role.split("/")[-1]
    out += ["## IAM", "",
            f"The pods use the function's execution role `{role}`. `iam/trust-policy.json` keeps the Lambda trust and adds EKS. To apply it:", "",
            "```bash", f"aws iam update-assume-role-policy --role-name {role_name} --policy-document file://iam/trust-policy.json"]
    if iam_mode == "pod-identity":
        out += [f"aws eks create-pod-identity-association --cluster-name CLUSTER --namespace {namespace} \\",
                f"  --service-account {plan.k8s_name} --role-arn {role}"]
    out += ["```", ""]
    if plan.iam_actions:
        out += ["The AI review found the code calling these actions. Compare them with the role's policies for least privilege:", "",
                ", ".join(f"`{a}`" for a in plan.iam_actions), ""]
    if any(w.kind == SQS for w in plan.workloads):
        out += ["KEDA reads queue depth with the same role. " + (
            "With `identityOwner: workload` it uses the ServiceAccount's IRSA role." if iam_mode == "irsa" else
            "With Pod Identity, the KEDA operator's own role must be allowed to `sts:AssumeRole` into this role."), ""]

    out += ["## Build and deploy", "", "```bash", "./build.sh                      # builds and pushes " + plan.image,
            "kubectl apply -k k8s/", "```", ""]
    placeholders = sorted({m for docs in files.values() for m in re.findall(r"REPLACE_ME\w*", dump_yaml(docs))})
    if placeholders or plan.secret_env_keys:
        out += ["Before applying, fill in:", ""]
        if plan.secret_env_keys:
            out.append(f"- Secret values in `k8s/secret.yaml`: {', '.join(plan.secret_env_keys)}")
        if placeholders:
            out.append(f"- Placeholders in `k8s/`: {', '.join(placeholders)}")
        out.append("")
    notes = spec.warnings + plan.ai_notes
    if notes:
        out += ["## Warnings", ""] + [f"- {n}" for n in notes] + [""]
    out += ["## Behaviour differences to know", "",
            f"- One pod runs {plan.concurrency} invocation(s) at a time." + (
                " Lambda scaled per request; here the HPA scales on CPU, which lags behind sudden bursts." if kinds & {HTTP, INVOKE} else ""),
            "- A timed-out invocation gets a 504 (HTTP) or a failed batch (SQS), but the handler code keeps running until it returns.",
            "- Logs go to stdout. Ship them with Fluent Bit or CloudWatch Container Insights if dashboards and alarms read CloudWatch Logs.",
            ""]
    return "\n".join(out)


def _patch_name(i: int, file: str) -> str:
    return f"{i:02d}-" + re.sub(r"[^A-Za-z0-9._-]+", "_", file)[:80] + ".diff"


def write_plan(plan: Plan, out: Path, namespace: str, region: str | None, iam_mode: str, ai_result: dict[str, Any] | None) -> None:
    out.mkdir(parents=True, exist_ok=True)
    region = region or plan.spec.region or "REPLACE_ME_REGION"
    files: dict[str, list[dict[str, Any]]] = {}
    if plan.supported:
        write_build_context(plan, out)
        files = manifests(plan, namespace, region, iam_mode)
        k8s = out / "k8s"
        if k8s.exists():
            shutil.rmtree(k8s)
        k8s.mkdir()
        for name, docs in files.items():
            (k8s / name).write_text(dump_yaml(docs))
        (k8s / "kustomization.yaml").write_text(dump_yaml([{
            "apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization",
            "namespace": namespace, "resources": sorted(files),
        }]))
        (out / "iam").mkdir(exist_ok=True)
        (out / "iam" / "trust-policy.json").write_text(json.dumps(trust_policy(plan, namespace, iam_mode), indent=2) + "\n")

    patch_files = []
    if ai_result is not None:
        ai_dir = out / "ai"
        if ai_dir.exists():
            shutil.rmtree(ai_dir)
        (ai_dir / "patches").mkdir(parents=True)
        (ai_dir / "review.json").write_text(json.dumps(ai_result, indent=2) + "\n")
        for i, change in enumerate(plan.code_changes, 1):
            name = _patch_name(i, change["file"])
            patch = change["patch"] if change["patch"].endswith("\n") else change["patch"] + "\n"
            (ai_dir / "patches" / name).write_text(f"# {change['description']}\n{patch}")
            patch_files.append(f"ai/patches/{name}")
    (out / "MIGRATION.md").write_text(report(plan, namespace, iam_mode, files, patch_files))
