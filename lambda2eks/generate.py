class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data: Any) -> bool:
        return True


def _str_presenter(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_presenter)


def dump_yaml(docs: list[dict[str, Any]]) -> str:
    return "---\n".join(yaml.dump(d, Dumper=_Dumper, sort_keys=False, default_flow_style=False) for d in docs)


# ------------------------------------------------------------------ build context

def runtime_tag(runtime: str) -> str:
    if runtime.startswith("python"):
        return runtime.removeprefix("python")
    m = re.match(r"nodejs(\d+)", runtime)
    if not m:
        raise ValueError(f"no base image for runtime {runtime}")
    return m.group(1)


def dockerfile(plan: Plan, src_present: bool) -> str:
    spec = plan.spec
    family = spec.runtime_family
    lines = ["# Generated by lambda2eks. The Lambda base image keeps the runtime, OS libraries and AWS SDK the function had."]
    if spec.image_uri:
        lines.append(f"FROM {spec.image_uri}")
    elif family == "python":
        lines += [f"FROM public.ecr.aws/lambda/python:{runtime_tag(spec.runtime)}", "COPY src/ ${LAMBDA_TASK_ROOT}/"]
        if src_present and not spec.prebuilt and (spec.code_dir / "requirements.txt").is_file():
            lines.append("RUN pip install --no-cache-dir -r ${LAMBDA_TASK_ROOT}/requirements.txt -t ${LAMBDA_TASK_ROOT}")
    else:
        lines += [f"FROM public.ecr.aws/lambda/nodejs:{runtime_tag(spec.runtime)}", "COPY src/ ${LAMBDA_TASK_ROOT}/"]
        if src_present and not spec.prebuilt and (spec.code_dir / "package.json").is_file():
            lock = (spec.code_dir / "package-lock.json").is_file()
            lines.append("RUN cd ${LAMBDA_TASK_ROOT} && " + ("npm ci --omit=dev" if lock else "npm install --omit=dev"))
    if family == "python":
        lines += [
            "COPY lambda2eks-shim.py /opt/lambda2eks/shim.py",
            "ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PYTHONPATH=/var/task:/var/runtime",
            "USER 1000:1000",
            'ENTRYPOINT ["python3", "/opt/lambda2eks/shim.py"]',
        ]
    else:
        # Lambda's bootstrap script sets NODE_PATH, and the Lambda build of Node honours it for ES modules too.
        # The shim replaces that script, so without this `import ... from '@aws-sdk/...'` (and layers) fail.
        major = runtime_tag(spec.runtime) if spec.runtime and spec.runtime.startswith("nodejs") else None
        node_path = ([f"/opt/nodejs/node{major}/node_modules"] if major else []) + \
                    ["/opt/nodejs/node_modules", "/var/runtime/node_modules", "/var/runtime", "/var/task"]
        lines += [
            f"ENV NODE_PATH={':'.join(node_path)}",
            "COPY lambda2eks-shim.mjs /opt/lambda2eks/shim.mjs",
            "USER 1000:1000",
            'ENTRYPOINT ["node", "/opt/lambda2eks/shim.mjs"]',
        ]
    lines.append("CMD []")
    return "\n".join(lines) + "\n"


def write_build_context(plan: Plan, out: Path) -> None:
    spec = plan.spec
    src_dst = out / "src"
    src_present = bool(spec.code_dir and spec.code_dir.is_dir())
    if src_present and spec.code_dir.resolve() != src_dst.resolve():
        if src_dst.exists():
            shutil.rmtree(src_dst)
        has_pkg = (spec.code_dir / "package.json").is_file()
        ignore = shutil.ignore_patterns(".aws-sam", ".git", "__pycache__", ".venv", "*.pyc", ".env*",
                                        *(["node_modules"] if has_pkg else []))
        shutil.copytree(spec.code_dir, src_dst, ignore=ignore)
    elif not spec.image_uri:
        src_dst.mkdir(exist_ok=True)

    shim = "shim.py" if spec.runtime_family == "python" else "shim.mjs"
    (out / f"lambda2eks-{shim}").write_text(resources.files("lambda2eks.shims").joinpath(shim).read_text())
    (out / "Dockerfile").write_text(dockerfile(plan, src_present))
    (out / ".dockerignore").write_text("k8s/\nhelm/\niam/\ninfra/\ncutover/\nai/\nMIGRATION.md\nbuild.sh\n")
    build = out / "build.sh"
    build.write_text(
        "#!/usr/bin/env bash\n"
        "# Build and push the image for this function. Override IMAGE to change the destination.\n"
        "set -euo pipefail\n"
        f'IMAGE="${{IMAGE:-{plan.image}}}"\n'
        'cd "$(dirname "$0")"\n'
        f'docker buildx build --platform linux/{spec.arch} -t "$IMAGE" --push .\n'
    )
    build.chmod(0o755)


# ------------------------------------------------------------------ manifests

def _labels(plan: Plan, component: str | None = None) -> dict[str, str]:
    labels = {"app.kubernetes.io/name": plan.k8s_name, "app.kubernetes.io/managed-by": "lambda2eks"}
    if component:
        labels["app.kubernetes.io/component"] = component
    return labels


def _base_env(plan: Plan, mode: str, region: str) -> list[dict[str, str]]:
    spec = plan.spec
    env = {
        "L2E_MODE": mode,
        "L2E_HANDLER": spec.handler or "REPLACE_ME",
        "L2E_TIMEOUT_S": str(spec.timeout_s),
        "L2E_CONCURRENCY": str(plan.concurrency),
        "AWS_LAMBDA_FUNCTION_NAME": spec.name,
        "AWS_LAMBDA_FUNCTION_MEMORY_SIZE": str(spec.memory_mb),
        "AWS_LAMBDA_FUNCTION_VERSION": "$LATEST",
        "AWS_REGION": region,
        "AWS_DEFAULT_REGION": region,
    }
    if spec.account_id:
        env["L2E_ACCOUNT_ID"] = spec.account_id
    if spec.runtime_family == "node" and "NODE_OPTIONS" not in spec.environment:
        # The heap sizing Lambda's bootstrap applies, from the pod's memory limit: V8 collects garbage
        # before the container reaches its limit instead of being OOM-killed.
        new_space = plan.memory_mb // 10
        env["NODE_OPTIONS"] = f"--max-semi-space-size={new_space // 6} --max-old-space-size={plan.memory_mb - new_space}"
    return [{"name": k, "value": v} for k, v in env.items()]


def _pod_spec(plan: Plan, workload: Workload, mode_env: list[dict[str, str]], region: str,
              http: bool, restart: str | None = None, grace: int = 30) -> dict[str, Any]:
    spec = plan.spec
    env_from = []
    if set(spec.environment) - set(plan.secret_env_keys):
        env_from.append({"configMapRef": {"name": f"{plan.k8s_name}-env"}})
    if plan.secret_env_keys:
        env_from.append({"secretRef": {"name": f"{plan.k8s_name}-secrets"}})
    container: dict[str, Any] = {
        "name": "function",
        "image": plan.image,
        "env": _base_env(plan, workload_mode(workload), region) + mode_env,
        **({"envFrom": env_from} if env_from else {}),
        "resources": {
            "requests": {"cpu": f"{plan.cpu_millicores}m", "memory": f"{pod_memory_mb(plan, workload)}Mi"},
            "limits": {"memory": f"{pod_memory_mb(plan, workload)}Mi"},
        },
        "securityContext": {
            "runAsNonRoot": True, "runAsUser": 1000, "runAsGroup": 1000, "readOnlyRootFilesystem": True,
            "allowPrivilegeEscalation": False, "capabilities": {"drop": ["ALL"]},
        },
        "volumeMounts": [{"name": "tmp", "mountPath": "/tmp"}],
    }
    if http:
        container["ports"] = [{"name": "http", "containerPort": PORT}]
        probe = {"httpGet": {"path": HEALTH_PATH, "port": "http"}, "periodSeconds": 10}
        container["readinessProbe"] = {**probe, "initialDelaySeconds": 2}
        container["livenessProbe"] = {**probe, "initialDelaySeconds": 10, "failureThreshold": 6}
    pod: dict[str, Any] = {
        "serviceAccountName": plan.k8s_name,
        "terminationGracePeriodSeconds": grace,
        "containers": [container],
        "volumes": [{"name": "tmp", "emptyDir": {"sizeLimit": f"{spec.ephemeral_storage_mb}Mi"}}],
        "nodeSelector": {"kubernetes.io/arch": spec.arch},
    }
    if restart:
        pod["restartPolicy"] = restart
    return pod


# On Lambda the queue and stream pollers run outside the function's sandbox, so its memory setting
# covers the handler only. Here the shim polls inside the same container: SDK clients, lease
# bookkeeping and an in-flight batch. A 128 MB stream consumer was OOM-killed without this.
POLLER_OVERHEAD_MB = {"sqs": 64, "stream": 96, "activity": 64}


def pod_memory_mb(plan: Plan, workload: Workload) -> int:
    return plan.memory_mb + POLLER_OVERHEAD_MB.get(workload_mode(workload), 0)


def workload_mode(w: Workload) -> str:
    return {HTTP: "http", INVOKE: "http", SQS: "sqs", S3: "sqs", SNS: "sqs", SCHEDULE: "schedule",
            KINESIS: "stream", DYNAMODB: "stream", SFN: "activity"}[w.kind]


class Target:
    """Where the workloads run: the resolved region and account, and generation options."""

    def __init__(self, plan: Plan, namespace: str, region: str, iam_mode: str, live: bool = False,
                 certificate_arn: str | None = None):
        self.namespace, self.region, self.iam_mode, self.live, self.certificate_arn = namespace, region, iam_mode, live, certificate_arn
        self.account = plan.spec.account_id or "REPLACE_ME_ACCOUNT"

    def queue_url(self, name: str) -> str:
        return f"https://sqs.{self.region}.amazonaws.com/{self.account}/{name}"

    def queue_arn(self, name: str) -> str:
        return f"arn:aws:sqs:{self.region}:{self.account}:{name}"

    def lease_table(self, plan: Plan) -> str:
        return f"l2e-{plan.k8s_name}-leases"

    def lease_table_arn(self, plan: Plan) -> str:
        return f"arn:aws:dynamodb:{self.region}:{self.account}:table/{self.lease_table(plan)}"

    def activity_name(self, plan: Plan) -> str:
        return f"l2e-{plan.k8s_name}"

    def activity_arn(self, plan: Plan) -> str:
        return f"arn:aws:states:{self.region}:{self.account}:activity:{self.activity_name(plan)}"


def _deployment(plan: Plan, w: Workload, replicas: int, pod: dict[str, Any]) -> dict[str, Any]:
    labels = _labels(plan, w.name)
    return {
        "apiVersion": "apps/v1", "kind": "Deployment",
        "metadata": {"name": w.name, "labels": labels},
        "spec": {
            "replicas": replicas,
            "selector": {"matchLabels": {"app.kubernetes.io/name": plan.k8s_name, "app.kubernetes.io/component": w.name}},
            "template": {"metadata": {"labels": labels}, "spec": pod},
        },
    }


def _ingress_paths(routes: list[dict[str, Any]]) -> list[str]:
    prefixes = set()
    for r in routes:
        p = r.get("path")
        if not p:
            return ["/"]
        head = p.split("{", 1)[0].rstrip("/") or "/"
        prefixes.add(head)
    return sorted(prefixes)


def http_docs(plan: Plan, w: Workload, t: Target) -> list[dict[str, Any]]:
    spec = plan.spec
    mode_env = [{"name": "L2E_PORT", "value": str(PORT)}]
    if w.kind == HTTP:
        mode_env += [
            {"name": "L2E_HTTP_EVENT_FORMAT", "value": w.trigger.details["event_format"]},
            {"name": "L2E_HTTP_ROUTES", "value": json.dumps([r for r in w.trigger.details["routes"] if r.get("path")])},
        ]
    grace = max(30, spec.timeout_s + 10)
    docs = [_deployment(plan, w, plan.http_min_replicas, _pod_spec(plan, w, mode_env, t.region, http=True, grace=grace))]
    selector = {"app.kubernetes.io/name": plan.k8s_name, "app.kubernetes.io/component": w.name}
    docs.append({
        "apiVersion": "v1", "kind": "Service",
        "metadata": {"name": w.name, "labels": _labels(plan, w.name)},
        "spec": {"selector": selector, "ports": [{"name": "http", "port": 80, "targetPort": "http"}]},
    })
    docs.append({
        "apiVersion": "autoscaling/v2", "kind": "HorizontalPodAutoscaler",
        "metadata": {"name": w.name, "labels": _labels(plan, w.name)},
        "spec": {
            "scaleTargetRef": {"apiVersion": "apps/v1", "kind": "Deployment", "name": w.name},
            "minReplicas": plan.http_min_replicas, "maxReplicas": plan.http_max_replicas,
            "metrics": [{"type": "Resource", "resource": {"name": "cpu", "target": {"type": "Utilization", "averageUtilization": 70}}}],
        },
    })
    if plan.http_min_replicas >= 2:
        docs.append({
            "apiVersion": "policy/v1", "kind": "PodDisruptionBudget",
            "metadata": {"name": w.name, "labels": _labels(plan, w.name)},
            "spec": {"minAvailable": 1, "selector": {"matchLabels": selector}},
        })
    if w.kind == HTTP:
        idle = max(60, spec.timeout_s + 5)
        annotations = {
            "alb.ingress.kubernetes.io/scheme": plan.ingress_scheme,
            "alb.ingress.kubernetes.io/target-type": "ip",
            "alb.ingress.kubernetes.io/healthcheck-path": HEALTH_PATH,
            "alb.ingress.kubernetes.io/load-balancer-attributes": f"idle_timeout.timeout_seconds={idle}",
        }
        if t.certificate_arn:
            annotations.update({
                "alb.ingress.kubernetes.io/listen-ports": '[{"HTTP": 80}, {"HTTPS": 443}]',
                "alb.ingress.kubernetes.io/certificate-arn": t.certificate_arn,
                "alb.ingress.kubernetes.io/ssl-redirect": "443",
            })
        docs.append({
            "apiVersion": "networking.k8s.io/v1", "kind": "Ingress",
            "metadata": {"name": w.name, "labels": _labels(plan, w.name), "annotations": annotations},
            "spec": {"ingressClassName": "alb", "rules": [{"http": {"paths": [
                {"path": p, "pathType": "Prefix", "backend": {"service": {"name": w.name, "port": {"name": "http"}}}}
                for p in _ingress_paths(w.trigger.details["routes"])
            ]}}]},
        })
    return docs


def _keda_auth(plan: Plan, w: Workload, t: Target) -> dict[str, Any]:
    pod_identity: dict[str, Any] = {"provider": "aws"}
    if t.iam_mode == "irsa":
        pod_identity["identityOwner"] = "workload"
    else:
        pod_identity["roleArn"] = plan.spec.role_arn or "REPLACE_ME"
    return {"apiVersion": "keda.sh/v1alpha1", "kind": "TriggerAuthentication",
            "metadata": {"name": w.name, "labels": _labels(plan, w.name)}, "spec": {"podIdentity": pod_identity}}


def _scaled_object(plan: Plan, w: Workload, t: Target, min_r: int, max_r: int, trigger: dict[str, Any]) -> dict[str, Any]:
    meta: dict[str, Any] = {"name": w.name, "labels": _labels(plan, w.name)}
    if not t.live:
        # Nothing consumes until the cut-over; CUTOVER.md removes this annotation at the right moment.
        meta["annotations"] = {PAUSED: "0"}
    return {
        "apiVersion": "keda.sh/v1alpha1", "kind": "ScaledObject", "metadata": meta,
        "spec": {
            "scaleTargetRef": {"name": w.name}, "minReplicaCount": min_r, "maxReplicaCount": max_r,
            "pollingInterval": 15, "cooldownPeriod": 300,
            "triggers": [{**trigger, "authenticationRef": {"name": w.name}}],
        },
    }


def sqs_docs(plan: Plan, w: Workload, t: Target) -> list[dict[str, Any]]:
    d = w.trigger.details
    if w.kind in BRIDGED:
        url, arn, batch = t.queue_url(w.bridge_queue), t.queue_arn(w.bridge_queue), 10
        mode_env = [{"name": "L2E_SQS_UNWRAP", "value": w.kind}]
        if d.get("subscription_arn"):
            mode_env.append({"name": "L2E_SNS_SUBSCRIPTION_ARN", "value": d["subscription_arn"]})
    else:
        url, arn, batch = d.get("queue_url") or "REPLACE_ME", d.get("queue_arn") or "", int(d.get("batch_size", 10))
        mode_env = [{"name": "L2E_SQS_REPORT_BATCH_ITEM_FAILURES", "value": "true" if d.get("report_batch_item_failures") else "false"}]
    mode_env = [{"name": "L2E_SQS_QUEUE_URL", "value": url}, {"name": "L2E_SQS_QUEUE_ARN", "value": arn},
                {"name": "L2E_SQS_BATCH_SIZE", "value": str(batch)}] + mode_env
    grace = plan.spec.timeout_s + 30  # one long poll (20 s) plus the batch in flight
    per_pod = (1 if w.kind in BRIDGED else max(1, min(batch, 10))) * plan.concurrency
    return [
        _deployment(plan, w, 0 if not t.live else 1, _pod_spec(plan, w, mode_env, t.region, http=False, grace=grace)),
        _keda_auth(plan, w, t),
        _scaled_object(plan, w, t, 0, plan.sqs_max_replicas, {"type": "aws-sqs-queue", "metadata": {
            "queueURL": url, "queueLength": str(per_pod), "awsRegion": t.region}}),
    ]


def stream_docs(plan: Plan, w: Workload, t: Target) -> list[dict[str, Any]]:
    d = w.trigger.details
    limit = 10000 if w.kind == KINESIS else 1000  # GetRecords maximums
    mode_env = [
        {"name": "L2E_STREAM_KIND", "value": w.kind},
        # For a cut-over the start is a timestamp CUTOVER.md sets; the Lambda's starting position would
        # replay the stream's whole retention (TRIM_HORIZON) or skip records written during the switch (LATEST).
        {"name": "L2E_STREAM_STARTING_POSITION", "value": d.get("starting_position") or "LATEST" if t.live else "LATEST"},
        {"name": "L2E_STREAM_BATCH_SIZE", "value": str(max(1, min(int(d.get("batch_size", 100)), limit)))},
        {"name": "L2E_STREAM_MAX_RETRY", "value": str(d.get("max_retry_attempts", -1))},
        {"name": "L2E_STREAM_BISECT", "value": "true" if d.get("bisect_on_error") else "false"},
        {"name": "L2E_STREAM_REPORT_BATCH_ITEM_FAILURES", "value": "true" if d.get("report_batch_item_failures") else "false"},
        *([{"name": "L2E_STREAM_START_TIMESTAMP", "value": str(d["starting_timestamp"])}]
          if t.live and d.get("starting_position") == "AT_TIMESTAMP" and d.get("starting_timestamp") else []),
        {"name": "L2E_LEASE_TABLE", "value": t.lease_table(plan)},
        {"name": "L2E_CONSUMER_NAME", "value": w.name},
        {"name": "L2E_ROLE_ARN", "value": plan.spec.role_arn or ""},
    ]
    if w.kind == KINESIS:
        mode_env += [{"name": "L2E_STREAM_NAME", "value": d.get("stream_name") or "REPLACE_ME"},
                     {"name": "L2E_STREAM_ARN", "value": d.get("stream_arn") or ""}]
        scaler = {"type": "aws-kinesis-stream", "metadata": {
            "streamName": d.get("stream_name") or "REPLACE_ME", "shardCount": "1", "awsRegion": t.region}}
    else:
        mode_env += [{"name": "L2E_DDB_TABLE", "value": d.get("table_name") or "REPLACE_ME"},
                     {"name": "L2E_STREAM_ARN", "value": d.get("stream_arn") or ""}]
        scaler = {"type": "aws-dynamodb-streams", "metadata": {
            "tableName": d.get("table_name") or "REPLACE_ME", "shardCount": "1", "awsRegion": t.region}}
    grace = plan.spec.timeout_s + 40  # finish the batch in flight, checkpoint, release the leases
    return [
        _deployment(plan, w, 0 if not t.live else 1, _pod_spec(plan, w, mode_env, t.region, http=False, grace=grace)),
        _keda_auth(plan, w, t),
        _scaled_object(plan, w, t, 1, plan.stream_max_replicas, scaler),
    ]


def schedule_docs(plan: Plan, w: Workload, t: Target) -> list[dict[str, Any]]:
    d = w.trigger.details
    try:
        cron, warns = to_k8s_cron(d["expression"])
    except ScheduleError as e:
        cron, warns = "0 0 31 2 *", [f"{e}; the CronJob is set to a date that never occurs and suspended until you fix it"]
        d["suspended"] = True
    tz = d.get("timezone") or "Etc/UTC"
    once = at_time(d["expression"], tz)
    if once and once < datetime.now(timezone.utc) and not d.get("suspended"):
        warns.append(f"{d['expression']} ({tz}) is in the past, so the one-time schedule has already run; the CronJob is suspended")
        d["suspended"] = True
    plan.spec.warnings.extend(w_ for w_ in warns if w_ not in plan.spec.warnings)
    scheduler = d.get("source") == "scheduler"
    mode_env = [{"name": "L2E_SCHEDULE_SOURCE", "value": "scheduler" if scheduler else "eventbridge-rule"}]
    if d.get("input"):
        mode_env.append({"name": "L2E_SCHEDULE_INPUT", "value": d["input"]})
    if d.get("rule_arn"):
        mode_env.append({"name": "L2E_SCHEDULE_RULE_ARN", "value": d["rule_arn"]})
    if scheduler:
        arn = d.get("schedule_arn") or (f"arn:aws:scheduler:{t.region}:{t.account}:schedule/{d.get('group_name') or 'default'}/"
                                        f"{d.get('schedule_name') or 'REPLACE_ME_SCHEDULE'}")
        mode_env.append({"name": "L2E_SCHEDULE_ARN", "value": arn})
    years = schedule_years(d["expression"])
    if years:
        # Kubernetes cron has no year: the CronJob fires every year in this slot and the shim skips other years.
        mode_env += [{"name": "L2E_SCHEDULE_YEARS", "value": years}, {"name": "L2E_SCHEDULE_TZ", "value": tz}]
    pod = _pod_spec(plan, w, mode_env, t.region, http=False, restart="Never")
    labels = _labels(plan, w.name)
    annotations = {"lambda2eks/scheduler-schedule" if scheduler else "lambda2eks/eventbridge-schedule": d["expression"]}
    if d.get("suspended"):
        annotations["lambda2eks/note"] = ("the one-time schedule has passed or was disabled; keep this suspended" if once else
                                          "the EventBridge schedule was disabled; keep this suspended")
    return [{
        "apiVersion": "batch/v1", "kind": "CronJob",
        "metadata": {"name": w.name, "labels": labels, "annotations": annotations},
        "spec": {
            # Suspended until the cut-over disables the EventBridge rule, so the job never runs twice.
            "schedule": cron, "timeZone": tz, "suspend": bool(d.get("suspended")) or not t.live,
            "concurrencyPolicy": plan.schedule_concurrency_policy, "startingDeadlineSeconds": 300,
            "successfulJobsHistoryLimit": 3, "failedJobsHistoryLimit": 3,
            "jobTemplate": {"spec": {
                "backoffLimit": 2,  # Lambda retries a failed asynchronous invocation twice
                "activeDeadlineSeconds": plan.spec.timeout_s + 120,
                "ttlSecondsAfterFinished": 86400,
                "template": {"metadata": {"labels": labels}, "spec": pod},
            }},
        },
    }]


def sfn_docs(plan: Plan, w: Workload, t: Target) -> list[dict[str, Any]]:
    mode_env = [{"name": "L2E_SFN_ACTIVITY_ARN", "value": t.activity_arn(plan)},
                {"name": "L2E_SFN_HEARTBEAT_S", "value": "20"}]
    # The workers can run before the cut-over: nothing reaches the activity until the state machine is switched to it.
    grace = plan.spec.timeout_s + 70  # a long poll (up to 60 s) can hand over one more task after SIGTERM
    return [_deployment(plan, w, plan.sfn_replicas, _pod_spec(plan, w, mode_env, t.region, http=False, grace=grace))]


def sfn_rewrites(plan: Plan, t: Target) -> dict[str, tuple[dict[str, Any], list[str], list[str], dict[str, Any]]]:
    """state machine name -> (definition calling the activity, rewritten states, notes, trigger details)."""
    out = {}
    for w in (w for w in plan.workloads if w.kind == SFN):
        for d in w.trigger.details["machines"]:
            name = machine_name(d.get("state_machine_arn") or d.get("state_machine_name") or "state-machine")
            new, done, notes = rewrite(d["definition"], plan.spec.name, d.get("refs") or [], t.activity_arn(plan), plan.spec.timeout_s)
            out[name] = (new, done, notes, d)
    return out


def manifests(plan: Plan, namespace: str, region: str, iam_mode: str, live: bool = False,
              certificate_arn: str | None = None) -> dict[str, list[dict[str, Any]]]:
    spec = plan.spec
    t = Target(plan, namespace, region, iam_mode, live, certificate_arn)
    sa: dict[str, Any] = {"apiVersion": "v1", "kind": "ServiceAccount", "metadata": {"name": plan.k8s_name, "labels": _labels(plan)}}
    if iam_mode == "irsa":
        sa["metadata"]["annotations"] = {"eks.amazonaws.com/role-arn": spec.role_arn or "REPLACE_ME"}
    files: dict[str, list[dict[str, Any]]] = {"serviceaccount.yaml": [sa]}
    plain = {k: v for k, v in sorted(spec.environment.items()) if k not in plan.secret_env_keys}
    if plain:
        files["configmap.yaml"] = [{"apiVersion": "v1", "kind": "ConfigMap",
                                    "metadata": {"name": f"{plan.k8s_name}-env", "labels": _labels(plan)}, "data": plain}]
    if plan.secret_env_keys:
        files["secret.yaml"] = [{
            "apiVersion": "v1", "kind": "Secret", "type": "Opaque",
            "metadata": {"name": f"{plan.k8s_name}-secrets", "labels": _labels(plan),
                         "annotations": {"lambda2eks/note": "values are placeholders; load them from Secrets Manager or External Secrets"}},
            "stringData": {k: "REPLACE_ME" for k in plan.secret_env_keys},
        }]
    for w in plan.workloads:
        if w.kind in (HTTP, INVOKE):
            files[f"{w.name}.yaml"] = http_docs(plan, w, t)
        elif w.kind in (SQS, *BRIDGED):
            files[f"{w.name}.yaml"] = sqs_docs(plan, w, t)
        elif w.kind in STREAMS:
            files[f"{w.name}.yaml"] = stream_docs(plan, w, t)
        elif w.kind == SCHEDULE:
            files[f"{w.name}.yaml"] = schedule_docs(plan, w, t)
        elif w.kind == SFN:
            files[f"{w.name}.yaml"] = sfn_docs(plan, w, t)
    return files


def trust_policy(plan: Plan, namespace: str, iam_mode: str) -> dict[str, Any]:
    # Keep Lambda's own trust so the function keeps working until the cut-over is finished.
    statements: list[dict[str, Any]] = [
        {"Sid": "KeepLambdaDuringMigration", "Effect": "Allow", "Principal": {"Service": "lambda.amazonaws.com"}, "Action": "sts:AssumeRole"},
    ]
    if iam_mode == "irsa":
        provider = "oidc.eks.REGION.amazonaws.com/id/REPLACE_ME_OIDC_ID"
        statements.append({
            "Sid": "EksIrsa", "Effect": "Allow",
            "Principal": {"Federated": f"arn:aws:iam::{plan.spec.account_id or 'ACCOUNT_ID'}:oidc-provider/{provider}"},
            "Action": "sts:AssumeRoleWithWebIdentity",
            "Condition": {"StringEquals": {f"{provider}:sub": f"system:serviceaccount:{namespace}:{plan.k8s_name}",
                                           f"{provider}:aud": "sts.amazonaws.com"}},
        })
    else:
        statements.append({"Sid": "EksPodIdentity", "Effect": "Allow", "Principal": {"Service": "pods.eks.amazonaws.com"},
                           "Action": ["sts:AssumeRole", "sts:TagSession"]})
    return {"Version": "2012-10-17", "Statement": statements}


